"""Generate docs/RESULTS.md from the saved metrics so the numbers in the docs always match the run.

Run after the pipelines:  python ml/src/make_report.py
"""
from __future__ import annotations

import json
from datetime import date

import pandas as pd

from common import REPO_ROOT, RESULTS_DIR

DOCS = REPO_ROOT / "docs"


def fmt(m, s=None):
    return f"{m:.3f} ± {s:.3f}" if s is not None and pd.notna(s) else f"{m:.3f}"


def table(summary: pd.DataFrame) -> str:
    rows = ["| Family | Model | ROC-AUC | Balanced acc. | Sensitivity | Specificity | F1 | Accuracy |",
            "|---|---|---|---|---|---|---|---|"]
    for _, r in summary.iterrows():
        rows.append(f"| {r.family} | {r.model.split(' | ', 1)[1].replace(' | ', ' · ')} | {fmt(r.roc_auc, r.roc_auc_std)} | "
                    f"{fmt(r.balanced_accuracy, r.balanced_accuracy_std)} | {fmt(r.sensitivity, r.sensitivity_std)} | "
                    f"{fmt(r.specificity, r.specificity_std)} | {fmt(r.f1, r.f1_std)} | {fmt(r.accuracy, r.accuracy_std)} |")
    return "\n".join(rows)


def img(task, name, alt):
    return f"![{alt}](../ml/results/{task}/{name})"


def section(task: str, title: str, protocol: str) -> str:
    d = RESULTS_DIR / task
    s = json.loads((d / "summary.json").read_text())
    summ = pd.read_csv(d / "metrics_summary.csv")
    b = s["best_model_metrics"]
    cm = s["best_model_pooled_confusion"]
    uni_best = summ[summ.family == "Unimodal"].iloc[0]
    out = [f"## {title}", "",
           f"**Data:** {s['n_samples']} samples, {s['n_positive']} positive "
           f"({s['n_positive'] / s['n_samples']:.1%}). Majority-class accuracy baseline = "
           f"{s['majority_baseline_accuracy']:.3f}.  ",
           f"**Modalities:** " + ", ".join(f"{k} ({v} features)" for k, v in s["views"].items()) + "  ",
           f"**Protocol:** {protocol}", "",
           "### Headline", "",
           f"* **Best model:** `{s['best_model']}`, ROC-AUC **{fmt(b['roc_auc'], b['roc_auc_std'])}**, "
           f"balanced accuracy **{fmt(b['balanced_accuracy'], b['balanced_accuracy_std'])}**, "
           f"sensitivity {b['sensitivity']:.3f}, specificity {b['specificity']:.3f}.",
           f"* **Best single modality:** `{uni_best.model}`, ROC-AUC {fmt(uni_best.roc_auc, uni_best.roc_auc_std)}, "
           f"balanced accuracy {fmt(uni_best.balanced_accuracy, uni_best.balanced_accuracy_std)}.",
           f"* **Gain from fusion:** {s['fusion_gain_auc_vs_best_unimodal']:+.3f} ROC-AUC over the best single modality."]
    if s.get("best_model_pooled_auc_95ci"):
        lo, hi = s["best_model_pooled_auc_95ci"]
        out.append(f"* Pooled out-of-fold ROC-AUC 95% bootstrap CI: [{lo:.3f}, {hi:.3f}].")
    out.append(f"* Pooled confusion matrix of the best model: TP={cm['tp']}, FN={cm['fn']}, TN={cm['tn']}, FP={cm['fp']}.")
    if "by_device" in s:
        out.append("* Best model by device: " + "; ".join(
            f"{k}: n={v['n']}, AUC {v['roc_auc']:.3f}, balanced acc. {v['balanced_accuracy']:.3f}"
            for k, v in s["by_device"].items()) + ".")
    out += ["", "### All models (mean ± sd over outer test folds)", "", table(summ), "",
            img(task, "model_comparison_auc.png", "ROC-AUC comparison"), "",
            img(task, "model_comparison_balacc.png", "Balanced accuracy comparison"), "",
            img(task, "roc_best_per_family.png", "ROC curves"), " ",
            img(task, "confusion_best.png", "Confusion matrix"), "",
            "### How late fusion weighted the modalities", "",
            img(task, "fusion_weights.png", "Late-fusion weights"), ""]
    return "\n".join(out), s


def main():
    parts = ["# Results - Multimodal Fusion & Explainable AI", "",
             f"_Auto-generated by `ml/src/make_report.py` on {date.today().isoformat()} from `ml/results/`. "
             "Do not edit by hand - re-run the pipelines and this script instead._", "",
             "All numbers are **held-out** (outer-fold test) estimates from nested cross-validation; "
             "every model choice, fusion weight, meta-learner and decision threshold was fitted on the "
             "training side of each outer fold only. See [ML_METHODOLOGY.md](ML_METHODOLOGY.md) for the method.", ""]

    dl, s_dl = section("dyslexia", "1. Dyslexia (game-interaction data)",
                       "nested CV - 5 outer folds x 5 inner folds, stratified.")
    parts += [dl, "### Explainability", "",
              "**Which modality matters?** Share of total mean |SHAP| of the early-fusion XGBoost:", "",
              "| Modality | Share |", "|---|---|"]
    parts += [f"| {k} | {v:.1%} |" for k, v in sorted(s_dl["xai"]["modality_share"].items(), key=lambda x: -x[1])]
    parts += ["", img("dyslexia", "xai_modality_importance.png", "Modality importance"), "",
              "**Top features (mean |SHAP|):** " + ", ".join(f"`{k}`" for k in list(s_dl["xai"]["top_features"])[:10]), "",
              img("dyslexia", "xai_shap_beeswarm.png", "SHAP beeswarm"), "",
              "**Most diagnostic game questions** (sum of |SHAP| over each question's features): " +
              ", ".join(f"{k}" for k in s_dl["xai"]["top_questions"]), "",
              img("dyslexia", "xai_question_importance.png", "Question importance"), "",
              "**Local explanation of one child** - feature-level (SHAP waterfall) and modality-level (late-fusion "
              "log-odds contributions):", "",
              img("dyslexia", "xai_shap_local_example.png", "Local SHAP"), " ",
              img("dyslexia", "xai_late_fusion_local_example.png", "Local late fusion"), ""]

    dg, s_dg = section("dysgraphia", "2. Dysgraphia (handwriting images)",
                       "nested CV - 5 outer folds x 3 repeats (15 test folds) x 5 inner folds, stratified.")
    gpi = s_dg["xai"]["grouped_permutation_auc_drop"]
    parts += [dg, "### Explainability", "",
              "**Which modality matters?** Drop in held-out ROC-AUC of the best early-fusion model when all "
              "features of one modality are shuffled together (grouped permutation importance):", "",
              "| Modality | AUC drop (mean ± sd) |", "|---|---|"]
    parts += [f"| {k} | {m:.3f} ± {sd:.3f} |" for k, (m, sd) in gpi.items()]
    dirs = s_dg["xai"]["geometry_direction_corr"]
    parts += ["", img("dysgraphia", "xai_modality_importance.png", "Modality importance"), "",
              "**Most influential handwriting-geometry features** (direction: ↑ = higher value pushes towards "
              "dysgraphia):", "", "| Feature | mean \\|SHAP\\| | Direction |", "|---|---|---|"]
    parts += [f"| `{k}` | {v:.4f} | {'↑' if dirs.get(k, 0) > 0 else '↓'} |"
              for k, v in s_dg["xai"]["geometry_top_features"].items()]
    parts += ["", img("dysgraphia", "xai_shap_geometry_beeswarm.png", "Geometry SHAP"), "",
              "**Where in the handwriting does the CNN look?** Occlusion sensitivity on held-out images:", "",
              img("dysgraphia", "xai_occlusion_maps.png", "Occlusion maps"), ""]

    dr, s_dr = section("dyscalculia_castaldi2024", "3a. Dyscalculia - real data (Castaldi et al. 2024)",
                       "nested CV - 5 outer folds x 10 repeats (50 test folds) x 3 inner folds, stratified.")
    parts += [dr.replace("### Headline", "> Source: Zenodo record 10966052 (CC BY 4.0). `math` (the diagnostic "
                         "criterion) and `reading` (46% missing, missingness tied to group) were excluded to avoid "
                         "label leakage. With 37 children these estimates are very uncertain.\n\n### Headline"),
              "### Explainability", "",
              img("dyscalculia_castaldi2024", "xai_shap_beeswarm.png", "SHAP"), "",
              "Top features: " + ", ".join(f"`{k}`" for k in s_dr["xai"]["top_features"]), ""]

    ds, s_ds = section("dyscalculia_synthetic", "3b. Dyscalculia - SYNTHETIC game telemetry",
                       "nested CV - 5 outer folds x 5 inner folds, stratified.")
    parts += [ds.replace("### Headline", "> **Simulated data.** These numbers test the pipeline and the XAI; they say "
                         "nothing about real children and must not be reported as clinical performance. Generator: "
                         "`ml/src/dyscalculia_synthetic.py`.\n\n### Headline"),
              f"**Best AUC possible given the 5% label noise:** {s_ds['label_noise_auc_ceiling']:.3f} "
              "(scoring every child by their true simulated status).", "",
              "### XAI check against the planted effects", "",
              "Planted deficits (SD): arithmetic/symbolic -1.4, ANS (magnitude, number line) -1.0, speed -0.3, "
              "subitizing -0.3, attention -0.2. The explanation should rank arithmetic/sequence features first, "
              "number-sense features next and subitizing last.", "",
              "| Modality | Share of mean abs. SHAP |", "|---|---|"]
    parts += [f"| {k} | {v:.1%} |" for k, v in sorted(s_ds["xai"]["modality_share"].items(), key=lambda x: -x[1])]
    parts += ["", "Top features: " + ", ".join(f"`{k}`" for k in list(s_ds["xai"]["top_features"])[:8]), "",
              img("dyscalculia_synthetic", "xai_shap_beeswarm.png", "SHAP"), ""]

    card = json.loads((REPO_ROOT / "ml" / "models" / "screening_system_card.json").read_text())
    parts += ["## 4. Main screening model", "",
              "`ml/src/main_model.py` (`ScreeningSystem`) wraps the best model per disorder, maps probability to the "
              "backend's risk levels and combines them like `AssessmentScoringService.synthesizeOverall`. "
              "MODERATE_TENDENCY starts at the balanced-accuracy threshold; HIGH_RISK starts where 95% of true "
              "negatives score lower.", "",
              "| Disorder | Model | CV ROC-AUC | Balanced acc. | MODERATE from | HIGH from | Trained on |",
              "|---|---|---|---|---|---|---|"]
    parts += [f"| {d} | {c['model'].replace(' | ', ' · ')} | {c['cv_roc_auc']:.3f} | {c['cv_balanced_accuracy']:.3f} | "
              f"p >= {c['moderate_threshold']:.2f} | p >= {c['high_threshold']:.2f} | "
              f"{'**synthetic**' if c['synthetic_training_data'] else 'real'} |" for d, c in card.items()]
    parts += [""]
    DOCS.mkdir(exist_ok=True)
    (DOCS / "RESULTS.md").write_text("\n".join(parts), encoding="utf-8")
    print("wrote", DOCS / "RESULTS.md")


if __name__ == "__main__":
    main()
